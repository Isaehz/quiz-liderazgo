export function resolveProfile(answers) {
  const counts = { A: 0, B: 0, C: 0 };
  for (const answer of answers) {
    if (counts[answer] !== undefined) counts[answer]++;
  }

  const { A, B, C } = counts;

  // Clear majorities (3 or more)
  if (A >= 3) return profiles.estrategico;
  if (B >= 3) return profiles.transformacional;
  if (C >= 3) return profiles.servicial;

  // Ties with 5 questions (e.g. 2-2-1)
  if (A === 2 && B === 2) return profiles.visionario_estrategico;
  if (B === 2 && C === 2) return profiles.mentor_humano;
  if (A === 2 && C === 2) return profiles.mentor_humano;

  return profiles.transformacional;
}
